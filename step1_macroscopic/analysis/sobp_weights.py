#!/usr/bin/env python3
"""Optimise SOBP weights from simulated pristine Bragg curves and write a GPS macro.

The pristine curves (dose per primary) come from pristine_scan.mac. Weights w_i
(relative numbers of primaries) are found by non-negative least squares so that
sum_i w_i D_i(z) is flat between the proximal and distal depths.

Example:
    python3 sobp_weights.py output/pristine_*MeV_depth.csv \
        --proximal 100 --distal 150 --output sobp.mac
"""

import argparse
import re
import sys
from pathlib import Path

import numpy as np

from step1_io import load_depth


def nnls(A, b, max_iter=None):
    """Lawson-Hanson active-set solution of min ||A x - b||, x >= 0."""
    m, n = A.shape
    max_iter = max_iter or 30 * n
    tol = 10 * np.finfo(float).eps * np.linalg.norm(A, 1) * max(m, n)
    passive = np.zeros(n, dtype=bool)
    x = np.zeros(n)
    w = A.T @ (b - A @ x)
    iterations = 0
    while (~passive).any() and w[~passive].max() > tol:
        j = int(np.argmax(np.where(passive, -np.inf, w)))
        passive[j] = True
        while True:
            iterations += 1
            if iterations > max_iter:
                raise RuntimeError("NNLS did not converge")
            s = np.zeros(n)
            s[passive] = np.linalg.lstsq(A[:, passive], b, rcond=None)[0]
            if s[passive].min() > 0:
                break
            mask = passive & (s <= 0)
            alpha = np.min(x[mask] / (x[mask] - s[mask]))
            x = x + alpha * (s - x)
            passive &= x > tol
            x[~passive] = 0.0
        x = s
        w = A.T @ (b - A @ x)
    return x


def energy_from_name(path):
    match = re.search(r"_(\d+(?:\.\d+)?)MeV", Path(path).name)
    if not match:
        raise ValueError(f"cannot read the energy from {path}; use --energies")
    return float(match.group(1))


def gps_source_block(command, weight, energy, sigma_rel, beam_sigma_mm):
    return "\n".join([
        f"{command} {weight:.6g}",
        "/gps/particle proton",
        "/gps/pos/type Beam",
        "/gps/pos/centre 0 0 -1 cm",
        f"/gps/pos/sigma_x {beam_sigma_mm} mm",
        f"/gps/pos/sigma_y {beam_sigma_mm} mm",
        "/gps/direction 0 0 1",
        "/gps/ene/type Gauss",
        f"/gps/ene/mono {energy:g} MeV",
        f"/gps/ene/sigma {sigma_rel * energy:.6g} MeV",
        "",
    ])


def write_macro(path, energies, weights, args):
    header = f"""# SOBP {args.proximal:g}-{args.distal:g} mm generated by sobp_weights.py
# Weights = relative numbers of primaries per energy (GPS normalises them)

/control/verbose 1
/run/verbose 1

/rbe/det/depth 40 cm
/rbe/det/width 40 cm
/rbe/det/maxStep 0.5 mm

/run/setCut 0.1 mm
/run/initialize

"""
    blocks = []
    first = True
    for energy, weight in zip(energies, weights):
        if weight <= 0:
            continue
        command = "/gps/source/intensity" if first else "/gps/source/add"
        blocks.append(gps_source_block(command, weight, energy, args.energy_spread, args.beam_sigma))
        first = False
    footer = f"""/rbe/score/depthBins 800
/rbe/score/spectrumDepthBins 200
/rbe/output/prefix {args.prefix}

/run/printProgress 10000
/run/beamOn {args.events}
"""
    Path(path).write_text(header + "\n".join(blocks) + footer)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("files", nargs="+", help="pristine *_depth.csv files")
    parser.add_argument("--energies", type=float, nargs="+", help="energies (MeV) matching files; default: from file names")
    parser.add_argument("--proximal", type=float, required=True, help="proximal SOBP edge (mm)")
    parser.add_argument("--distal", type=float, required=True, help="distal SOBP edge (mm)")
    parser.add_argument("--margin", type=float, default=2.0,
                        help="accept pristine peaks this far (mm) outside the SOBP region (default 2)")
    parser.add_argument("--energy-spread", type=float, default=0.005, help="relative energy sigma (default 0.005)")
    parser.add_argument("--beam-sigma", type=float, default=3.0, help="lateral beam sigma in mm (default 3)")
    parser.add_argument("--events", type=int, default=100000)
    parser.add_argument("--prefix", default="output/sobp")
    parser.add_argument("--output", default="sobp.mac")
    parser.add_argument("--curve", help="optional CSV of the predicted SOBP curve")
    args = parser.parse_args(argv)

    energies = args.energies or [energy_from_name(f) for f in args.files]
    if len(energies) != len(args.files):
        parser.error("number of --energies must match the number of files")
    order = np.argsort(energies)[::-1]
    energies = [energies[i] for i in order]
    curves = [load_depth(args.files[i]) for i in order]

    z = curves[0]["z_mid_mm"]
    for c in curves[1:]:
        if not np.allclose(c["z_mid_mm"], z):
            sys.exit("all pristine curves must use the same depth binning")
    dose = np.column_stack([c["dose_Gy"] for c in curves])

    # Only peaks inside the SOBP region may be used: the fit ignores the dose
    # proximal to the region, so it would otherwise exploit the distal tails of
    # low-energy peaks and put huge doses upstream.
    peaks = z[np.argmax(dose, axis=0)]
    usable = (peaks >= args.proximal - args.margin) & (peaks <= args.distal + args.margin)
    for e, p, ok in zip(energies, peaks, usable):
        if not ok:
            print(f"skipping {e:g} MeV: peak at {p:.1f} mm is outside the SOBP region")
    if not usable.any():
        sys.exit("no pristine peak inside the SOBP region")
    if peaks[usable].max() < args.distal - args.margin:
        print("warning: no pristine peak near the distal edge; extend the energy basis")
    energies = [e for e, ok in zip(energies, usable) if ok]
    dose = dose[:, usable]

    region = (z >= args.proximal) & (z <= args.distal)
    if not region.any():
        sys.exit("no depth bins inside the requested SOBP region")

    # Scale columns to unit peak for conditioning, target a flat dose of 1
    scale = dose.max(axis=0)
    scale[scale == 0] = 1.0
    A = dose[region] / scale
    w = nnls(A, np.ones(region.sum())) / scale
    w /= w.max()

    sobp = dose @ w
    plateau = sobp[region]
    flatness = (plateau.max() - plateau.min()) / plateau.mean()
    print(f"{'E (MeV)':>9} {'weight':>10}")
    for e, wi in zip(energies, w):
        print(f"{e:9.2f} {wi:10.4f}")
    print(f"flatness (max-min)/mean over {args.proximal:g}-{args.distal:g} mm: {100 * flatness:.2f} %")

    write_macro(args.output, energies, w, args)
    print(f"GPS macro written to {args.output}")
    if args.curve:
        np.savetxt(args.curve, np.column_stack([z, sobp / plateau.mean()]), delimiter=",",
                   header="z_mid_mm,relative_dose", comments="")


if __name__ == "__main__":
    main()
